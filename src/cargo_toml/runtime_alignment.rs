//! One `windjammer-runtime` per dependency graph.
//!
//! Generated manifests (`build/Cargo.toml` of a Windjammer package) name the runtime crate by an absolute path.
//! A package built earlier (another `wj` binary, another temp dir, a parallel run) can carry a different path
//! than the test or app crate that now depends on it; cargo then refuses the graph ("package collision in the
//! lockfile: windjammer-runtime ... are different"). Before such a crate is built, every generated manifest
//! reachable through `path` dependencies is pointed at the runtime the root crate uses.

use std::collections::HashSet;
use std::path::{Path, PathBuf};

const GENERATED_HEADER: &str = "# Auto-generated by Windjammer compiler";

/// `path = "..."` of a dependency line (`name = { path = "../x", ... }`), if it has one.
fn dependency_path(line: &str) -> Option<&str> {
    let (name, rest) = line.split_once('=')?;
    if name.trim() == "path" || name.trim().is_empty() {
        return None;
    }
    let after = rest.split("path = \"").nth(1)?;
    Some(&after[..after.find('"')?])
}

fn is_runtime_line(line: &str) -> bool {
    line.trim_start().starts_with("windjammer-runtime") && line.contains("path = \"")
}

fn with_runtime_path(line: &str, runtime: &str) -> String {
    let start = line.find("path = \"").map(|i| i + "path = \"".len()).unwrap_or(0);
    let end = line[start..].find('"').map(|i| i + start).unwrap_or(start);
    format!("{}{}{}", &line[..start], runtime, &line[end..])
}

/// Walk the `path` dependencies reachable from `root_manifest` and point the `windjammer-runtime` line of every
/// compiler-generated manifest at `runtime`. Hand-written manifests (no generated header) are never edited.
/// Returns the manifests that were rewritten.
pub(crate) fn align_path_dependencies_to_runtime(root_manifest: &Path, runtime: &Path) -> Vec<PathBuf> {
    let runtime = super::path_to_toml_string(runtime);
    let mut rewritten = Vec::new();
    let mut seen = HashSet::new();
    let mut todo = vec![root_manifest.to_path_buf()];
    while let Some(manifest) = todo.pop() {
        let Ok(canon) = manifest.canonicalize() else { continue };
        if !seen.insert(canon) {
            continue;
        }
        let Ok(text) = std::fs::read_to_string(&manifest) else { continue };
        let dir = manifest.parent().unwrap_or(Path::new("."));
        for line in text.lines() {
            if let Some(p) = dependency_path(line) {
                if !is_runtime_line(line) {
                    todo.push(dir.join(p).join("Cargo.toml"));
                }
            }
        }
        if manifest != root_manifest && text.starts_with(GENERATED_HEADER) {
            let mut changed = false;
            let lines: Vec<String> = text
                .lines()
                .map(|l| {
                    if is_runtime_line(l) {
                        let new = with_runtime_path(l, &runtime);
                        changed |= new != l;
                        new
                    } else {
                        l.to_string()
                    }
                })
                .collect();
            if changed && std::fs::write(&manifest, lines.join("\n") + "\n").is_ok() {
                rewritten.push(manifest);
            }
        }
    }
    rewritten
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    fn write(p: &Path, s: &str) {
        fs::create_dir_all(p.parent().unwrap()).unwrap();
        fs::write(p, s).unwrap();
    }

    fn generated(rt: &str, dep: Option<&str>) -> String {
        let mut s = format!("{GENERATED_HEADER} - do not edit manually\n[package]\nname = \"p\"\n[dependencies]\n");
        s.push_str(&format!("windjammer-runtime = {{ path = \"{rt}\", default-features = false }}\n"));
        if let Some(d) = dep {
            s.push_str(&format!("q = {{ path = \"{d}\" }}\n"));
        }
        s
    }

    #[test]
    fn stale_runtime_paths_are_rewritten_transitively() {
        let t = tempfile::tempdir().unwrap();
        let r = t.path();
        write(&r.join("root/Cargo.toml"), "[package]\nname = \"root\"\n[dependencies]\nwindjammer-runtime = { path = \"/new/rt\" }\na = { path = \"../a\" }\n");
        write(&r.join("a/Cargo.toml"), &generated("/old/rt1", Some("../b")));
        write(&r.join("b/Cargo.toml"), &generated("/old/rt2", None));
        let done = align_path_dependencies_to_runtime(&r.join("root/Cargo.toml"), Path::new("/new/rt"));
        assert_eq!(done.len(), 2);
        for d in ["a", "b"] {
            let text = fs::read_to_string(r.join(d).join("Cargo.toml")).unwrap();
            assert!(text.contains("windjammer-runtime = { path = \"/new/rt\", default-features = false }"), "{text}");
            assert!(!text.contains("/old/"), "{text}");
        }
        // the root manifest is the caller's; it is never edited
        assert!(fs::read_to_string(r.join("root/Cargo.toml")).unwrap().contains("/new/rt"));
        // idempotent
        assert!(align_path_dependencies_to_runtime(&r.join("root/Cargo.toml"), Path::new("/new/rt")).is_empty());
    }

    #[test]
    fn hand_written_manifests_and_cycles_are_left_alone() {
        let t = tempfile::tempdir().unwrap();
        let r = t.path();
        write(&r.join("root/Cargo.toml"), "[dependencies]\na = { path = \"../a\" }\n");
        let hand = "[package]\nname = \"a\"\n[dependencies]\nwindjammer-runtime = { path = \"/mine\" }\nroot = { path = \"../root\" }\n";
        write(&r.join("a/Cargo.toml"), hand);
        assert!(align_path_dependencies_to_runtime(&r.join("root/Cargo.toml"), Path::new("/new/rt")).is_empty());
        assert_eq!(fs::read_to_string(r.join("a/Cargo.toml")).unwrap(), hand);
    }
}
