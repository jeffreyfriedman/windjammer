//! `wj rust-surface`: generate a Rust crate's signature surface (ADR-0026) from the crate's source.
//!
//! Source of truth: the crate source Cargo unpacked (the version `Cargo.lock` locks), parsed with `syn`. That works
//! on stable Rust, offline, and is pinned by the lock file; rustdoc JSON needs nightly and its format changes
//! between toolchains (ADR-0026 "Generator"). Only signatures Windjammer can express are emitted ([`map`]); every
//! other public free function is listed as skipped with its reason. Generated functions have unknown authority
//! (`ffi(<crate>)`) unless the curated list ([`pure`]) marks the crate version pure.
//!
//! Output is a pure function of the crate source, the enabled features, the generator version and the curated list
//! (byte-identical across runs; nothing depends on time, threads or hash-map order).

pub mod cache;
mod cfg;
pub mod locate;
mod map;
pub mod pure;
mod scan;

use sha2::{Digest, Sha256};
use std::fmt::Write as _;

pub use locate::CrateSource;

/// Bumped whenever the output for the same crate source changes.
pub const GENERATOR_VERSION: u32 = 1;
/// First line of a surface generated into the cache. The repository gate rejects tracked files that carry it.
pub const CACHE_MARKER: &str = "// @generated by `wj rust-surface`";

/// One function the surface declares.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GenFn {
    pub name: String,
    pub doc: Option<String>,
    /// `(name, Windjammer type)`
    pub params: Vec<(String, String)>,
    pub ret: Option<String>,
}

/// The result of generating one crate's surface.
#[derive(Debug, Clone)]
pub struct Generated {
    pub crate_name: String,
    pub version: String,
    /// `sha256` over the source files read (relative path and contents, in path order).
    pub source_hash: String,
    pub fns: Vec<GenFn>,
    /// `(name, reason)`, sorted by name.
    pub skipped: Vec<(String, String)>,
    pub pure: pure::Verdict,
    pub notes: Vec<String>,
}

/// Generate the surface of `src`.
pub fn generate(src: &CrateSource) -> Result<Generated, String> {
    let s = scan::scan(&src.dir, &src.lib, &src.features)?;
    let mut fns = Vec::new();
    let mut skipped = s.skipped.clone();
    for f in &s.fns {
        match function(&f.name, &f.item, &s.aliases) {
            Ok(g) => fns.push(g),
            Err(why) => skipped.push((f.name.clone(), why)),
        }
    }
    fns.sort_by(|a, b| a.name.cmp(&b.name));
    fns.dedup_by(|a, b| a.name == b.name);
    skipped.sort();
    skipped.dedup_by(|a, b| a.0 == b.0);
    skipped.retain(|(n, _)| !fns.iter().any(|f| f.name == *n));
    let mut h = Sha256::new();
    for (path, text) in &s.files {
        h.update(path.as_bytes());
        h.update([0]);
        h.update(text.as_bytes());
        h.update([0]);
    }
    let source_hash = h.finalize().iter().fold(String::new(), |mut acc, b| {
        let _ = write!(acc, "{b:02x}");
        acc
    });
    let pure = pure::verdict(&src.name, &src.version, &s.files);
    Ok(Generated { crate_name: src.name.clone(), version: src.version.clone(), source_hash, fns, skipped, pure, notes: s.notes })
}

fn function(name: &str, f: &syn::ItemFn, aliases: &map::Aliases) -> Result<GenFn, String> {
    let sig = &f.sig;
    let generics: Vec<String> = sig
        .generics
        .params
        .iter()
        .filter(|p| !matches!(p, syn::GenericParam::Lifetime(_)))
        .map(map::show)
        .collect();
    if !generics.is_empty() {
        return Err(format!("generic over `{}`", generics.join(", ")));
    }
    if sig.asyncness.is_some() {
        return Err("is `async`".into());
    }
    if sig.unsafety.is_some() {
        return Err("is `unsafe`".into());
    }
    if sig.variadic.is_some() {
        return Err("is variadic".into());
    }
    if f.attrs.iter().any(|a| a.path().is_ident("doc") && map::show(&a.meta).contains("hidden")) {
        return Err("is `#[doc(hidden)]` (not public API)".into());
    }
    let mut params = Vec::new();
    for (i, input) in sig.inputs.iter().enumerate() {
        let syn::FnArg::Typed(pt) = input else { return Err("takes `self`".into()) };
        let pname = match pt.pat.as_ref() {
            syn::Pat::Ident(id) => id.ident.to_string().trim_start_matches('_').to_string(),
            _ => String::new(),
        };
        let pname = if pname.is_empty() { format!("arg{i}") } else { pname };
        let ty = map::param(&pt.ty, aliases).map_err(|why| format!("parameter `{pname}` {why}"))?;
        params.push((pname, ty));
    }
    let ret = map::ret(&sig.output, aliases)?;
    let doc = f.attrs.iter().find_map(doc_line);
    Ok(GenFn { name: name.to_string(), doc, params, ret })
}

fn doc_line(a: &syn::Attribute) -> Option<String> {
    let syn::Meta::NameValue(nv) = &a.meta else { return None };
    if !nv.path.is_ident("doc") {
        return None;
    }
    let syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) = &nv.value else { return None };
    let line = s.value().trim().to_string();
    (!line.is_empty()).then_some(line)
}

/// What the output depends on besides the crate source: `generator N, pure list M`.
pub fn stamp() -> String {
    format!("generator {GENERATOR_VERSION}, pure list {}", pure::list_version())
}

/// How the surface will be used.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    /// `.wj-cache/rust-surfaces/<crate>/surface.wji`: regenerated on demand, never committed.
    Cache,
    /// `rust/<crate>.wji` written by `--write`: source, edited and committed by people who pin or curate it.
    Pinned,
}

/// The surface text. `only` restricts the declared functions (`--fn`); skipped functions are always listed.
pub fn render(g: &Generated, mode: Mode, only: Option<&[String]>) -> String {
    let mut out = String::new();
    let cmd = format!("wj rust-surface {} --write", g.crate_name);
    match mode {
        Mode::Cache => {
            let _ = writeln!(out, "{CACHE_MARKER} ({}); cache file, never commit it", stamp());
            let _ = writeln!(out, "// to pin or curate it, `{cmd}` writes an editable copy to rust/{}.wji", g.crate_name);
        }
        Mode::Pinned => {
            let _ = writeln!(out, "// generated by `wj rust-surface` ({}); this copy is source: edit and commit it", stamp());
            let _ = writeln!(out, "// regenerate with `{cmd}` (hand edits are overwritten)");
        }
    }
    let _ = writeln!(out, "// crate: {} {}", g.crate_name, g.version);
    let _ = writeln!(out, "// source: sha256:{}", g.source_hash);
    let effects = match &g.pure {
        pure::Verdict::Pure => format!("@pure from the curated pure-crates list (v{})", pure::list_version()),
        pure::Verdict::Unlisted => format!("unknown authority: every call is ffi({}) (grant it in [capabilities])", g.crate_name),
        pure::Verdict::Refused(why) => format!("listed as pure but {why}: every call is ffi({})", g.crate_name),
    };
    let _ = writeln!(out, "// effects: {effects}");
    for f in g.fns.iter().filter(|f| only.is_none_or(|o| o.contains(&f.name))) {
        out.push('\n');
        if let Some(d) = &f.doc {
            let _ = writeln!(out, "/// {d}");
        }
        if g.pure == pure::Verdict::Pure {
            out.push_str("@pure\n");
        }
        let params: Vec<String> = f.params.iter().map(|(n, t)| format!("{n}: {t}")).collect();
        let _ = write!(out, "pub fn {}({})", f.name, params.join(", "));
        if let Some(r) = &f.ret {
            let _ = write!(out, " -> {r}");
        }
        out.push('\n');
    }
    if !g.skipped.is_empty() {
        let _ = writeln!(out, "\n// Not expressible in Windjammer yet; declare one by hand in rust/{}.wji to call it:", g.crate_name);
        for (n, why) in &g.skipped {
            let _ = writeln!(out, "// skipped {n}: {why}");
        }
    }
    for n in &g.notes {
        let _ = writeln!(out, "// note: {n}");
    }
    out
}

/// What a generated header records (`None` for a hand-written surface).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Header {
    pub crate_name: String,
    pub version: String,
    pub cache: bool,
    /// The [`stamp`] the file was generated with.
    pub stamp: String,
    /// 1-based line of `// crate: ..`.
    pub line: usize,
}

pub fn header(text: &str) -> Option<Header> {
    let mut lines = text.lines().take(6).enumerate();
    let (_, first) = lines.next()?;
    let cache = first.starts_with(CACHE_MARKER);
    if !cache && !first.starts_with("// generated by `wj rust-surface`") {
        return None;
    }
    let stamp = first.split_once('(').and_then(|(_, r)| r.split_once(')')).map(|(s, _)| s.to_string()).unwrap_or_default();
    let (i, rest) = lines.find_map(|(i, l)| l.strip_prefix("// crate: ").map(|r| (i, r)))?;
    let (name, version) = rest.split_once(' ')?;
    Some(Header { crate_name: name.to_string(), version: version.trim().to_string(), cache, stamp, line: i + 1 })
}

/// `(name, reason)` of the functions a generated surface lists as skipped.
pub fn skipped_in(text: &str) -> Vec<(String, String)> {
    text.lines()
        .filter_map(|l| l.strip_prefix("// skipped "))
        .filter_map(|l| l.split_once(": "))
        .map(|(n, w)| (n.to_string(), w.to_string()))
        .collect()
}

