//! JavaScript / TypeScript backends over the portable typed IR.
//!
//! Output is a ready-to-run directory: `main.mjs` (or `main.ts`), the runtime `wj_core.mjs`,
//! `package.json` (`"type": "module"`). See `MODULE.md`.

mod emit;
pub mod tree_shaker;

use crate::codegen::backend::{CodegenBackend, CodegenConfig, CodegenOutput, Target};
use crate::codegen::portable::{self, flatten};
use crate::parser::Program;
use anyhow::{anyhow, Result};
use emit::EmitOptions;

/// Runtime support file shipped next to every generated program.
pub const RUNTIME_SOURCE: &str = include_str!("../../../std/runtime/js/wj_core.mjs");
/// Portable `std::{math,strings,fs,time}` shims.
pub const STD_SOURCE: &str = include_str!("../../../std/runtime/js/wj_std.mjs");

/// Names exported by a runtime module (`export const $x` / `export function $x`).
fn exports_of(source: &'static str) -> Vec<&'static str> {
    source
        .lines()
        .filter_map(|l| {
            let rest = l.strip_prefix("export const ").or_else(|| l.strip_prefix("export function "))?;
            let end = rest.find(|c: char| !(c.is_alphanumeric() || c == '$' || c == '_'))?;
            Some(&rest[..end])
        })
        .collect()
}

fn import_from(source: &'static str, module: &str, body: &str) -> Option<String> {
    let used: Vec<&str> = exports_of(source).into_iter().filter(|n| body.contains(n)).collect();
    if used.is_empty() { None } else { Some(format!("import {{ {} }} from \"{module}\";\n", used.join(", "))) }
}

/// Prepend the runtime imports for the names the program uses.
fn with_runtime_import(body: String) -> String {
    let core = import_from(RUNTIME_SOURCE, "./wj_core.mjs", &body).unwrap_or_default();
    let std = import_from(STD_SOURCE, "./wj_std.mjs", &body).unwrap_or_default();
    format!("// Generated by the Windjammer JavaScript backend. Do not edit.\n{core}{std}\n{body}")
}

pub struct JavaScriptBackend {
    typescript: bool,
}

impl JavaScriptBackend {
    pub fn new() -> Self {
        Self { typescript: false }
    }

    /// The TypeScript flavour: same emitter, annotated output (`main.ts`).
    pub fn typescript() -> Self {
        Self { typescript: true }
    }

    fn lower(&self, program: &Program, config: &CodegenConfig) -> Result<portable::PModule> {
        let program = if config.tree_shake { tree_shaker::shake_tree(program) } else { program.clone() };
        let program = portable::prelude::with_arena_prelude(&program).unwrap_or(program);
        let ctx = crate::ir::analyze_and_lower(&program)?;
        let mut m = portable::lower::lower_program(&program, Some(&ctx.registry)).map_err(|e| anyhow!("{e}"))?;
        flatten::flatten_module(&mut m);
        Ok(m)
    }
}

impl Default for JavaScriptBackend {
    fn default() -> Self {
        Self::new()
    }
}

impl CodegenBackend for JavaScriptBackend {
    fn name(&self) -> &str {
        if self.typescript { "TypeScript" } else { "JavaScript" }
    }

    fn target(&self) -> Target {
        if self.typescript { Target::TypeScript } else { Target::JavaScript }
    }

    fn generate(&self, program: &Program, config: &CodegenConfig) -> Result<CodegenOutput> {
        let m = self.lower(program, config)?;
        let body = emit::emit_module(&m, &EmitOptions { typescript: self.typescript, capability_install: config.capability_install.clone() }).map_err(|e| anyhow!("{e}"))?;
        let ext = if self.typescript { "ts" } else { "mjs" };
        Ok(CodegenOutput::new(with_runtime_import(body), ext.to_string()))
    }

    fn generate_additional_files(&self, _program: &Program, _config: &CodegenConfig) -> Vec<(String, String)> {
        let entry = if self.typescript { "main.ts" } else { "main.mjs" };
        let pkg = format!("{{\n  \"name\": \"windjammer-program\",\n  \"version\": \"0.1.0\",\n  \"private\": true,\n  \"type\": \"module\",\n  \"main\": \"{entry}\",\n  \"scripts\": {{ \"start\": \"node {entry}\" }},\n  \"engines\": {{ \"node\": \">=22.6.0\" }}\n}}\n");
        vec![("wj_core.mjs".to_string(), RUNTIME_SOURCE.to_string()), ("wj_std.mjs".to_string(), STD_SOURCE.to_string()), ("package.json".to_string(), pkg)]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn runtime_exports_include_core_helpers() {
        let names = exports_of(RUNTIME_SOURCE);
        for n in ["$panic", "$i64", "$print", "$run"] {
            assert!(names.contains(&n), "missing {n}");
        }
        assert!(exports_of(STD_SOURCE).contains(&"$std_math_sqrt"));
    }

    #[test]
    fn import_lists_only_used_names() {
        let out = with_runtime_import("$print(\"x\");".to_string());
        assert!(out.contains("import { $print }"), "{out}");
        assert!(!out.contains("wj_std"), "{out}");
    }
}
