//! Typed Go emitter over the portable IR.
//!
//! Integers map to exact Go widths with checked arithmetic (panic on overflow, like Rust debug
//! builds); structs map to Go structs (value semantics are native, deep copies use `wjClone`);
//! enums are interfaces with one struct per variant; Option/Result/tuples are runtime generics
//! (`Option[T]`, `Result[T, E]`, `TupleN[...]`). All helpers live in `wj_core.go`.

mod builtin;
mod expr;
mod fmt;
mod items;
mod names;
mod num;
mod pat;
mod stmt;
mod types;

use crate::codegen::portable::ir::*;
use crate::codegen::portable::ty::Ty;
use std::collections::HashMap;

pub struct Go<'m> {
    pub m: &'m PModule,
    pub out: String,
    pub ind: usize,
    pub tmp: usize,
    /// Locals that are Go pointers (`&mut` params, pointer receivers): name -> pointee type.
    pub ptr_locals: HashMap<String, Ty>,
    /// Return type of the function being emitted.
    pub ret: Ty,
    /// Names of enclosing loops (labels), innermost last.
    pub loops: Vec<String>,
    pub used_labels: Vec<bool>,
}

/// Emit `main.go` for the module.
pub fn emit_module(m: &PModule) -> PResult<String> {
    let mut g = Go { m, out: String::new(), ind: 0, tmp: 0, ptr_locals: HashMap::new(), ret: Ty::Unit, loops: vec![], used_labels: vec![] };
    g.out.push_str("// Generated by the Windjammer Go backend. Do not edit.\npackage main\n\n");
    g.module()?;
    Ok(g.out)
}

impl<'m> Go<'m> {
    pub fn line(&mut self, s: &str) {
        for _ in 0..self.ind {
            self.out.push('\t');
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    pub fn fresh(&mut self, base: &str) -> String {
        self.tmp += 1;
        format!("wj{base}{}", self.tmp)
    }

    pub fn unsupported<T>(&self, what: impl Into<String>) -> PResult<T> {
        Err(Unsupported { what: what.into(), line: 0 })
    }

    /// Find a user function/method by owner and name.
    pub fn find_fn(&self, owner: Option<&str>, name: &str) -> Option<&'m PFn> {
        match owner {
            None => self.m.fns.iter().find(|f| f.name == name),
            Some(o) => {
                let from_struct = self.m.structs.iter().find(|s| s.name == o).and_then(|s| s.methods.iter().find(|f| f.name == name));
                let from_enum = self.m.enums.iter().find(|e| e.name == o).and_then(|e| e.methods.iter().find(|f| f.name == name));
                let from_trait = self.m.traits.iter().find(|t| t.name == o).and_then(|t| t.methods.iter().find(|f| f.name == name));
                from_struct.or(from_enum).or(from_trait)
            }
        }
    }
}
