// Generates ts-sandbox.html (ADR-0034): the TypeScript sandbox as one document with one inline script, so its CSP
// can name that script by hash and allow nothing else from any URL (no 'self': a program cannot even import() from
// this site). Sources: vendor/sucrase-3.35.0.min.mjs, ts-core.mjs, ts-sandbox.js. Each is wrapped in its own
// function scope, so the minified vendor names cannot collide with ours.
//
//   node docs/book/playground/build-ts-sandbox.mjs           write ts-sandbox.html
//   node docs/book/playground/build-ts-sandbox.mjs --check   exit 1 when ts-sandbox.html is stale
// Browser-only plumbing: JavaScript is the only language that can build this page (Windjammer has no JS bundler yet).

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => readFileSync(join(here, f), "utf8");

function replaceOnce(text, pattern, by, what) {
  const hits = text.match(new RegExp(pattern.source, pattern.flags.includes("g") ? pattern.flags : pattern.flags + "g"));
  if (!hits || hits.length !== 1) throw new Error(`${what}: expected exactly one match of ${pattern}, found ${hits ? hits.length : 0}`);
  return text.replace(pattern, by);
}

function sucrase() {
  let s = read("vendor/sucrase-3.35.0.min.mjs");
  let exported = null;
  s = replaceOnce(s, /export\{(\w+) as transform\};?\s*$/, (_, name) => {
    exported = name;
    return "";
  }, "sucrase bundle");
  return `const __sucrase = (() => {\n${s}\nreturn { transform: ${exported} };\n})();`;
}

function core() {
  let s = read("ts-core.mjs");
  s = replaceOnce(s, /^import \{ transform \} from "\.\/vendor\/sucrase-3\.35\.0\.min\.mjs";$/m, "const { transform } = __sucrase;", "ts-core.mjs");
  const names = [];
  s = s.replace(/^export (const|function) (\w+)/gm, (_, kind, name) => {
    names.push(name);
    return `${kind} ${name}`;
  });
  return `const __core = (() => {\n${s}\nreturn { ${names.join(", ")} };\n})();`;
}

function sandbox() {
  let s = read("ts-sandbox.js");
  s = replaceOnce(s, /^import \{ ([\w, ]+) \} from "\.\/ts-core\.mjs";$/m, (_, names) => `const { ${names} } = __core;`, "ts-sandbox.js");
  return `(() => {\n${s}\n})();`;
}

export function build() {
  // the hash covers the element's whole text, newlines included
  const script = "\n" + ["\"use strict\";", sucrase(), core(), sandbox()].join("\n") + "\n";
  if (/<\/script|<!--/i.test(script)) throw new Error("the inline script must not contain </script or <!--");
  const hash = createHash("sha256").update(script, "utf8").digest("base64");
  const csp = `default-src 'none'; script-src 'sha256-${hash}' blob:; worker-src blob:; connect-src 'none'; base-uri 'none'; form-action 'none'`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<!-- GENERATED by build-ts-sandbox.mjs from ts-sandbox.js, ts-core.mjs and vendor/ (ADR-0034); do not edit.
     Loaded only as <iframe sandbox="allow-scripts">: an opaque origin with no cookies, storage or parent DOM.
     The one script below is allowed by its hash; nothing is fetched from any URL (connect-src 'none', no 'self'),
     no eval. The Worker it creates from a blob: URL inherits this policy. -->
<meta http-equiv="Content-Security-Policy" content="${csp}">
<title>TypeScript sandbox</title>
</head>
<body>
<script>${script}</script>
</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = build();
  const target = join(here, "ts-sandbox.html");
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      /* missing */
    }
    if (current !== html) {
      process.stderr.write("ts-sandbox.html is stale: run node docs/book/playground/build-ts-sandbox.mjs\n");
      process.exit(1);
    }
    process.stdout.write("ts-sandbox.html is up to date\n");
  } else {
    writeFileSync(target, html);
    process.stdout.write(`wrote ${target} (${html.length} bytes)\n`);
  }
}
