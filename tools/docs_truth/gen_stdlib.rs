//! `docs/reference/stdlib.md`: public surface of `std/**/*.wj`, scanned line-wise.

use super::util::walk;
use super::Ctx;

fn item_line(l: &str) -> Option<&str> {
    let t = l.trim_start();
    let t = t.strip_prefix("pub ").unwrap_or(t);
    ["fn ", "async fn ", "struct ", "enum ", "trait ", "type ", "const "].iter().any(|p| t.starts_with(p)).then_some(t)
}

fn signature(lines: &[&str], i: usize) -> String {
    let mut sig = String::new();
    for l in lines.iter().skip(i).take(6) {
        let t = l.trim();
        let cut = t.find('{').unwrap_or(t.len());
        sig.push_str(t[..cut].trim_end());
        let balanced = sig.matches('(').count() == sig.matches(')').count();
        if cut < t.len() || t.ends_with(';') || balanced {
            break;
        }
        sig.push(' ');
    }
    sig.trim().trim_start_matches("pub ").trim_end_matches(';').trim().to_string()
}

pub fn stdlib(ctx: &Ctx) -> String {
    let mut s = String::from("# Standard library surface\n\nGenerated by scanning `std/**/*.wj` (declared items and their doc summaries). Bodies in `std/` are stubs; behaviour lives in the runtime.\n\n");
    let mut total = 0;
    for f in walk(&ctx.root.join("std")) {
        if !f.ends_with(".wj") || f.ends_with("_test.wj") || f.ends_with("_tests.wj") {
            continue;
        }
        let text = ctx.read(&format!("std/{f}"));
        let lines: Vec<&str> = text.lines().collect();
        let mut items = Vec::new();
        for (i, l) in lines.iter().enumerate() {
            if l.trim_start().starts_with("//") || item_line(l).is_none() {
                continue;
            }
            let doc = (0..i).rev().map_while(|j| lines[j].trim().strip_prefix("///")).last().map(|d| d.trim().to_string());
            let indent = if l.starts_with(' ') || l.starts_with('\t') { "  " } else { "" };
            items.push(format!("{indent}- `{}`{}", signature(&lines, i), doc.map(|d| format!(" - {d}")).unwrap_or_default()));
        }
        if items.is_empty() {
            continue;
        }
        total += items.len();
        s.push_str(&format!("## `std::{}`\n\n{}\n\n", f.trim_end_matches(".wj").replace('/', "::"), items.join("\n")));
    }
    s.push_str(&format!("{total} declared items.\n"));
    s
}
