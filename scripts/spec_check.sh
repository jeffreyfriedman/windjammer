#!/usr/bin/env bash
# spec-check: keep docs/spec rule IDs and tests/spec examples in lock-step.
#
#   scripts/spec_check.sh           verify (exit 1 on any problem)
#   scripts/spec_check.sh --write   also regenerate docs/spec/CONFORMANCE_MATRIX.md
#   scripts/spec_check.sh --run     verify, then run the executable examples and the grammar check (docs_truth)
#
# Rules: a rule is a line in docs/spec/*.md that starts with **SPEC-<AREA>-<NNN>**. It needs at least
# one tests/spec/**/*.wj example whose header has `// spec: SPEC-<AREA>-<NNN>`, unless the rule line
# contains "(untestable: <reason>)". Every `// spec:` reference must name a defined rule, and every
# `// xfail: Q-NNN` must name a `## Q-NNN` heading in docs/spec/OPEN_QUESTIONS.md.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
SPEC=docs/spec
TESTS=tests/spec
MATRIX=$SPEC/CONFORMANCE_MATRIX.md
write=0; run=0
for a in "$@"; do case "$a" in --write) write=1;; --run) run=1;; *) echo "unknown arg $a" >&2; exit 2;; esac; done

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
err=0
fail() { echo "spec-check: $*" >&2; err=1; }

# rule definitions: id <TAB> file <TAB> untestable-flag
grep -nE '^\*\*SPEC-[A-Z]+-[0-9]{3}\*\*' $SPEC/*.md /dev/null \
  | sed -E 's/^([^:]+):[0-9]+:\*\*(SPEC-[A-Z]+-[0-9]{3})\*\*(.*)$/\2\t\1\t\3/' \
  | awk -F'\t' '{u=($3 ~ /\(untestable:/)?"untestable":"testable"; print $1"\t"$2"\t"u}' | sort > "$tmp/rules.tsv"
dups=$(cut -f1 "$tmp/rules.tsv" | uniq -d || true)
[ -z "$dups" ] || fail "duplicate rule IDs: $dups"

# references: id <TAB> test file (only the leading comment header counts)
: > "$tmp/refs.tsv"; : > "$tmp/xfails.tsv"
while IFS= read -r f; do
  awk -v f="$f" '
    /^\/\// { if (match($0, /^\/\/ *spec: *SPEC-[A-Z]+-[0-9]+/)) { s=$0; sub(/^\/\/ *spec: */, "", s); sub(/[ \t].*$/, "", s); print s "\t" f > "/dev/stderr" }
              if (match($0, /^\/\/ *xfail: *Q-[0-9]+/)) { x=$0; sub(/^\/\/ *xfail: */, "", x); sub(/[ \t].*$/, "", x); print x "\t" f }
              next }
    /^[ \t]*$/ { next }
    { exit }' "$f" >> "$tmp/xfails.tsv" 2>> "$tmp/refs.tsv"
done < <(find $TESTS -name '*.wj' | sort)
sort -o "$tmp/refs.tsv" "$tmp/refs.tsv"

# unknown references
while IFS=$'\t' read -r id file; do
  grep -q "^$id	" "$tmp/rules.tsv" || fail "$file references unknown rule $id"
done < "$tmp/refs.tsv"
# untested rules
while IFS=$'\t' read -r id file flag; do
  if [ "$flag" = testable ] && ! grep -q "^$id	" "$tmp/refs.tsv"; then fail "rule $id ($file) has no test under $TESTS"; fi
done < "$tmp/rules.tsv"
# tests without any spec header
while IFS= read -r f; do
  grep -q "	$f\$" "$tmp/refs.tsv" || fail "$f has no '// spec: SPEC-...' header"
done < <(find $TESTS -name '*.wj' | sort)
# xfail targets
while IFS=$'\t' read -r q file; do
  grep -qE "^## $q( |\$)" $SPEC/OPEN_QUESTIONS.md || fail "$file: xfail $q has no '## $q' entry in OPEN_QUESTIONS.md"
done < "$tmp/xfails.tsv"

# every SPEC-ID mentioned in prose must exist
for id in $(grep -ohE 'SPEC-[A-Z]+-[0-9]{3}' $SPEC/*.md | sort -u); do
  grep -q "^$id	" "$tmp/rules.tsv" || fail "docs mention unknown rule $id"
done
# compact spec size budget (about 8k tokens at ~3.5 chars per token)
[ "$(wc -c < $SPEC/SPEC_COMPACT.md)" -le 28000 ] || fail "SPEC_COMPACT.md exceeds the 8k-token budget (28000 bytes)"

# conformance matrix
{
  echo "<!-- GENERATED by scripts/spec_check.sh --write; do not edit. -->"
  echo "# Conformance matrix"
  echo
  echo "Every normative rule and the executable examples (under \`tests/spec/\`) that check it."
  echo "\`xfail Q-NNN\` means the implementation contradicts the rule today; see OPEN_QUESTIONS.md."
  echo
  echo "| Rule | Chapter | Examples |"
  echo "|------|---------|----------|"
  while IFS=$'\t' read -r id file flag; do
    ex=$({ grep "^$id	" "$tmp/refs.tsv" || true; } | cut -f2 | while read -r t; do
      x=$(grep "	$t\$" "$tmp/xfails.tsv" | cut -f1 | head -1 || true)
      printf '`%s`%s<br>' "${t#$TESTS/}" "${x:+ (xfail $x)}"
    done)
    [ -n "$ex" ] || ex="untestable"
    echo "| $id | $(basename "$file") | ${ex%<br>} |"
  done < "$tmp/rules.tsv"
} > "$tmp/matrix.md"
if [ $write -eq 1 ]; then cp "$tmp/matrix.md" $MATRIX
elif ! cmp -s "$tmp/matrix.md" $MATRIX 2>/dev/null; then fail "$MATRIX is stale; run scripts/spec_check.sh --write"; fi

n=$(wc -l < "$tmp/rules.tsv" | tr -d ' ')
t=$(grep -c . "$tmp/refs.tsv" || true)
u=$(grep -c untestable "$tmp/rules.tsv" || true)
x=$(grep -c . "$tmp/xfails.tsv" || true)
echo "spec-check: $n rules, $t example references, $u untestable, $x xfail"
[ $err -eq 0 ] || exit 1
if [ $run -eq 1 ]; then
  cargo test --release --test spec_conformance
  cargo test --release --test docs_truth spec_grammar
fi
