#!/usr/bin/env bash
# Record the rustc oracle for the `wj check` negative gate (tests/check_negative_test.rs).
#   scripts/check-negative-oracle.sh [path/to/wj]
# For every program in the negative corpora: transpile with `wj build --no-cargo` and, when that
# succeeds, `cargo check` the generated crate. Writes tests/check_negative/oracle.tsv:
#   <path>  <fnv1a64 of source>  <transpile ok|fail>  <rustc ok|fail|skip>
# Entries whose source hash is unchanged are reused. The test itself never runs cargo; it compares `wj check` against this recorded oracle.
set -uo pipefail
cd "$(dirname "$0")/.."
WJ="${1:-wj}"
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-${TMPDIR:-/tmp}/wj-negative-target}"
OUT=tests/check_negative/oracle.tsv
TMP=$(mktemp)
for f in tests/check_negative/mutants/*.wj tests/diagnostics/cases/*.wj tests/error_system/*.wj tests/error_system_e2e/*.wj; do
  sha=$(python3 -c 'import sys
h=0xcbf29ce484222325
for b in open(sys.argv[1],"rb").read():
    h=((h^b)*0x100000001b3)&0xffffffffffffffff
print("%016x"%h)' "$f")
  prev=$(awk -F'\t' -v f="$f" -v h="$sha" '$1==f && $2==h' "$OUT" 2>/dev/null | head -1)
  if [ -n "$prev" ]; then printf '%s\n' "$prev" >> "$TMP"; continue; fi
  out=$(mktemp -d)
  if "$WJ" build "$f" -o "$out" --no-cargo >/dev/null 2>&1; then
    tr=ok
    if (cd "$out" && cargo check -q >/dev/null 2>&1); then rc=ok; else rc=fail; fi
  else
    tr=fail; rc=skip
  fi
  rm -rf "$out"
  printf '%s\t%s\t%s\t%s\n' "$f" "$sha" "$tr" "$rc" | tee -a "$TMP"
done
{ echo "# path	fnv1a64	transpile	rustc   (generated by scripts/check-negative-oracle.sh)"; sort "$TMP"; } > "$OUT"
rm -f "$TMP"
