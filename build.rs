/// Auto-generate the consolidated test module list from every test file under `tests/`.
///
/// Consolidating into a single binary eliminates ~800 separate link operations,
/// reducing full test suite time from 14+ minutes to 2-3 minutes. Adding a new
/// test file to `tests/` is all that's needed — no manual registration. The discovery
/// rule (top-level files, sub-directory files with `#[test]`, excluded dirs, name
/// collisions) lives in `build_support/test_modules.rs`.
fn generate_test_all_rs() {
    use std::fs;
    use std::path::Path;

    let tests_dir = Path::new("tests");
    if !tests_dir.is_dir() {
        return;
    }

    let modules = match test_modules::discover_test_modules(tests_dir) {
        Ok(modules) => modules,
        Err(message) => panic!("tests/ discovery failed: {message}"),
    };

    let out_dir = std::env::var("OUT_DIR").unwrap_or_else(|_| "target".to_string());
    let generated_path = Path::new(&out_dir).join("all_tests_generated.rs");

    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".to_string());
    let tests_dir_abs = Path::new(&manifest_dir).join("tests");

    /// Absolute path for `#[path = "..."]` in generated test modules.
    /// Forward slashes only; strip Windows `\\?\` prefix from canonicalize().
    fn path_for_attr(base: &Path, relative: &str) -> String {
        let path = base.join(relative);
        let abs = fs::canonicalize(&path).unwrap_or(path);
        let mut s = abs.display().to_string();
        if s.starts_with(r"\\?\") {
            s = s[4..].to_string();
        }
        s.replace('\\', "/")
    }

    let mut content = String::new();
    content.push_str("// AUTO-GENERATED by build.rs — do not edit.\n");
    content.push_str("// Consolidates all *_test.rs / *_tests.rs files into one binary\n");
    content.push_str("// to avoid ~800 separate link operations.\n\n");
    content
        .push_str("// Absolute paths with forward slashes — relative paths resolve from OUT_DIR\n");
    content.push_str(
        "// (not tests/), and Windows canonicalize() adds \\\\?\\ which breaks escapes.\n\n",
    );

    content.push_str(&format!(
        "#[path = \"{}\"]\nmod test_utils;\n\n",
        path_for_attr(&tests_dir_abs, "common/test_utils.rs")
    ));

    println!("cargo:rerun-if-changed=tests/common/test_utils.rs");
    for module in &modules {
        println!("cargo:rerun-if-changed=tests/{}", module.rel_path);
        content.push_str(&format!(
            "#[path = \"{}\"]\nmod {};\n\n",
            path_for_attr(&tests_dir_abs, &module.rel_path),
            module.name
        ));
    }

    stable_build::write_if_changed(&generated_path, &content).expect("write generated all_tests_generated.rs");
}

/// Emit `$OUT_DIR/embedded_assets_generated.rs`: byte tables for the runtime assets
/// (`std/`, `stdlib_meta/`, `crates/windjammer-runtime/`) so an installed `wj` never
/// reads them from a source checkout. See `src/embedded_assets.rs`.
fn generate_embedded_assets() {
    use std::fs;
    use std::path::Path;

    fn walk(dir: &Path, base: &Path, out: &mut Vec<(String, String)>) {
        let Ok(rd) = fs::read_dir(dir) else { return };
        let mut entries: Vec<_> = rd.flatten().collect();
        entries.sort_by_key(|e| e.file_name());
        for e in entries {
            let p = e.path();
            if p.is_dir() {
                walk(&p, base, out);
            } else {
                let rel = p
                    .strip_prefix(base)
                    .unwrap()
                    .to_string_lossy()
                    .replace('\\', "/");
                out.push((rel, p.to_string_lossy().replace('\\', "/")));
            }
        }
    }

    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".to_string());
    let manifest = Path::new(&manifest);
    let sets: [(&str, &str, &[&str]); 3] = [
        ("STDLIB_META", "stdlib_meta", &[""]),
        ("STD_WJ", "std", &[""]),
        (
            "RUNTIME_CRATE",
            "crates/windjammer-runtime",
            &["Cargo.toml", "src"],
        ),
    ];
    let mut code = String::new();
    for (name, dir, roots) in sets {
        let base = manifest.join(dir);
        println!("cargo:rerun-if-changed={}", base.display());
        let mut files = Vec::new();
        for r in roots {
            let p = base.join(r);
            if p.is_dir() {
                walk(&p, &base, &mut files);
            } else if p.is_file() {
                files.push((r.to_string(), p.to_string_lossy().replace('\\', "/")));
            }
        }
        code.push_str(&format!("pub static {name}: &[(&str, &[u8])] = &[\n"));
        let hashed = files.clone();
        for (rel, abs) in files {
            code.push_str(&format!("    ({rel:?}, include_bytes!({abs:?})),\n"));
        }
        code.push_str("];\n");
        // Content hash computed at build time (FNV-1a over paths + bytes): keys the cache dir.
        let mut h: u64 = 0xcbf29ce484222325;
        for (rel, abs) in &hashed {
            for b in rel
                .bytes()
                .chain([0u8])
                .chain(fs::read(abs).unwrap_or_default())
            {
                h ^= b as u64;
                h = h.wrapping_mul(0x100000001b3);
            }
        }
        code.push_str(&format!("pub const {name}_HASH: u64 = {h};\n"));
    }
    let out_dir = std::env::var("OUT_DIR").unwrap_or_else(|_| "target".to_string());
    // Only when the table changed: the library `include!`s this file, so a newer mtime alone recompiles it.
    stable_build::write_if_changed(&Path::new(&out_dir).join("embedded_assets_generated.rs"), &code)
        .expect("write embedded assets table");
}

/// Run `git <args>` in the manifest dir; `None` when git or the repository is unavailable.
fn git_output(args: &[&str]) -> Option<String> {
    let dir = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into());
    let out = stable_build::git_command(std::path::Path::new(&dir), args).output().ok()?;
    if !out.status.success() {
        return None;
    }
    Some(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// Toolchain identity (`wj --version`, `wj doctor`): commit hash, commit date, dirty flag, profile, build date.
/// Commit date (not wall-clock time) is the only time value that may reach generated output; the wall-clock
/// build date is read by `toolchain::identity` for `--version` alone (gate: tests/toolchain_identity_test.rs).
/// The build date is kept in OUT_DIR so it only changes when the commit or dirty flag does.
/// A rerun of this script recompiles the library (cargo treats a rerun as a changed dependency), so what it
/// watches is kept narrow: not `.git/index` (`git status` rewrites it), not the whole `tests/` tree.
fn emit_toolchain_identity() {
    use std::fs;
    use std::path::Path;
    // Not `index`: `git status` rewrites it, and the dirty state is already tracked through `src`, `std` and the test modules.
    for rel in ["HEAD", "packed-refs"] {
        if let Some(p) = git_output(&["rev-parse", "--git-path", rel]) {
            println!("cargo:rerun-if-changed={p}");
        }
    }
    if let Some(r) = git_output(&["symbolic-ref", "-q", "HEAD"]) {
        if let Some(p) = git_output(&["rev-parse", "--git-path", &r]) {
            println!("cargo:rerun-if-changed={p}");
        }
    }
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=std");
    let hash = git_output(&["rev-parse", "HEAD"]).unwrap_or_else(|| "unknown".into());
    let commit_ts: i64 = git_output(&["log", "-1", "--format=%ct"]).and_then(|s| s.parse().ok()).unwrap_or(0);
    let dirty = git_output(&["status", "--porcelain", "--untracked-files=no"]).is_some_and(|s| !s.is_empty());
    let profile = std::env::var("PROFILE").unwrap_or_else(|_| "unknown".into());
    // Uncommitted changes are part of the identity: two dirty builds of one commit are different binaries.
    let diff = if dirty { git_output(&["diff-index", "-p", "HEAD"]).unwrap_or_default() } else { String::new() };
    let untracked: Vec<(String, Vec<u8>)> = git_output(&["ls-files", "--others", "--exclude-standard", "--", "src", "std", "build.rs", "Cargo.toml"])
        .unwrap_or_default()
        .lines()
        .filter_map(|f| {
            let root = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into());
            Some((f.to_string(), std::fs::read(Path::new(&root).join(f)).ok()?))
        })
        .collect();
    let key = identity_key::identity_key(&hash, dirty, identity_key::dirty_digest(&diff, &untracked), &profile);
    let stamp = Path::new(&std::env::var("OUT_DIR").unwrap_or_else(|_| "target".into())).join("toolchain_identity.stamp");
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    let build_ts: i64 = match fs::read_to_string(&stamp).ok().and_then(|s| {
        let (k, t) = s.split_once('\n')?;
        (k == key).then(|| t.trim().parse().ok()).flatten()
    }) {
        Some(t) => t,
        None => {
            let _ = fs::write(&stamp, format!("{key}\n{now}\n"));
            now
        }
    };
    // content identity of the compiler source (no clock, no path): key of the cross-checkout analysis cache
    println!("cargo:rustc-env=WJ_BUILD_KEY={key}");
    println!("cargo:rustc-env=WJ_GIT_HASH={hash}");
    println!("cargo:rustc-env=WJ_GIT_TS={commit_ts}");
    println!("cargo:rustc-env=WJ_GIT_DIRTY={dirty}");
    println!("cargo:rustc-env=WJ_BUILD_PROFILE={profile}");
    println!("cargo:rustc-env=WJ_BUILD_TS={build_ts}");
}

/// macOS on Apple silicon: link `wj` with chained fixups, so dyld applies the binary's pointer fixups page by page as
/// it maps them instead of rebasing every pointer before `main` (4.3M of the 27.5M instructions `wj -V` retired; the
/// interpreter's startup ladder, ADR-0038 P2). Only the `wj` binary is linked differently: no dependency is rebuilt.
fn link_wj_with_chained_fixups() {
    let os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    if os == "macos" && arch == "aarch64" {
        println!("cargo:rustc-link-arg-bin=wj=-Wl,-fixup_chains");
    }
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    emit_toolchain_identity();
    generate_embedded_assets();
    // Not `tests` as a whole: cargo scans a watched directory recursively, and the test suite writes files
    // into it (tests/generated, per-project .wj-cache dirs, fixture scratch files), so every test run made
    // the next build dirty and recompiled the library. Only the discovered test modules are watched (in
    // `generate_test_all_rs`); a test file added later is caught by tests/build_rerun_stability_test.rs.
    println!("cargo:rerun-if-changed=build_support");
    println!("cargo::rustc-check-cfg=cfg(tarpaulin)");
    link_wj_with_chained_fixups();

    generate_test_all_rs();

    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();

    if target_os == "windows" {
        let target_env = std::env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
        let profile = std::env::var("PROFILE").unwrap_or_default();
        let crate_name = std::env::var("CARGO_PKG_NAME").unwrap_or_default();

        // 64MB stack - if this doesn't work, problem is structural
        let stack_size = 67108864;

        eprintln!("========================================");
        eprintln!("BUILD SCRIPT: Setting Windows stack size");
        eprintln!("  Package: {}", crate_name);
        eprintln!("  Profile: {}", profile);
        eprintln!("  Stack: {}MB", stack_size / 1048576);
        eprintln!("========================================");

        match target_env.as_str() {
            "msvc" => {
                println!("cargo:rustc-link-arg=/STACK:{}", stack_size);
                println!("cargo:rustc-link-arg=/DEBUG"); // Include debug info
            }
            "gnu" => {
                println!("cargo:rustc-link-arg=-Wl,--stack,{}", stack_size);
            }
            _ => {
                eprintln!("Warning: Unknown target environment: {}", target_env);
            }
        }
    }
}
