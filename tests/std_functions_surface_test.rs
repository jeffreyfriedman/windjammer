//! `src/stdlib_surface/std_functions_table.rs` lists, per std module, every function some engine provides. This gate
//! recomputes it from the sources and fails on drift; `WJ_UPDATE_STD_FUNCTIONS=1` rewrites the table.
//! Sources: top-level `fn`s of `std/<m>.wj` and `std/<m>/**/*.wj`, `pub fn`s at the top of
//! `crates/windjammer-runtime/src/<m>.rs` / `<m>_mod.rs`, and interpreter builtins registered as `func("<m>::f", ..)`.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

const SKIP: &[&str] = &["runtime", "basic_test", "test_simple"];

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn files(dir: &Path, ext: &str, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            files(&p, ext, out);
        } else if p.extension().is_some_and(|x| x == ext) {
            out.push(p);
        }
    }
}

fn ident(s: &str) -> Option<String> {
    let id: String = s.chars().take_while(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == '_').collect();
    (id.starts_with(|c: char| c.is_ascii_lowercase() || c == '_')).then_some(id)
}

/// Names declared by lines `[pub ][async ]fn name` at column 0 (`pub` required when `need_pub`).
fn top_fns(text: &str, need_pub: bool) -> Vec<String> {
    text.lines()
        .filter_map(|l| {
            let (l, is_pub) = match l.strip_prefix("pub ") {
                Some(r) => (r, true),
                None => (l, false),
            };
            if need_pub && !is_pub {
                return None;
            }
            ident(l.strip_prefix("async ").unwrap_or(l).strip_prefix("fn ")?)
        })
        .collect()
}

fn compute() -> BTreeMap<String, BTreeSet<String>> {
    let r = root();
    let mut modules = BTreeSet::new();
    for e in std::fs::read_dir(r.join("std")).unwrap().flatten() {
        let p = e.path();
        let name = if p.is_dir() { p.file_name() } else if p.extension().is_some_and(|x| x == "wj") { p.file_stem() } else { None };
        if let Some(n) = name {
            modules.insert(n.to_string_lossy().to_string());
        }
    }
    let mut interp = Vec::new();
    files(&r.join("src/interpreter"), "rs", &mut interp);
    let interp: Vec<String> = interp.iter().map(|p| std::fs::read_to_string(p).unwrap()).collect();
    let mut out = BTreeMap::new();
    for m in modules.iter().filter(|m| !SKIP.contains(&m.as_str())) {
        let mut fns = BTreeSet::new();
        let mut wj = vec![r.join("std").join(format!("{m}.wj"))];
        files(&r.join("std").join(m), "wj", &mut wj);
        for p in wj {
            fns.extend(top_fns(&std::fs::read_to_string(&p).unwrap_or_default(), false));
        }
        for p in [format!("{m}.rs"), format!("{m}_mod.rs")] {
            let text = std::fs::read_to_string(r.join("crates/windjammer-runtime/src").join(p)).unwrap_or_default();
            fns.extend(top_fns(&text, true));
        }
        let needle = format!("func(\"{m}::");
        for text in &interp {
            for (i, _) in text.match_indices(&needle) {
                let rest = &text[i + needle.len()..];
                if let Some(id) = ident(rest).filter(|id| rest[id.len()..].starts_with('"')) {
                    fns.insert(id);
                }
            }
        }
        if !fns.is_empty() {
            out.insert(m.clone(), fns);
        }
    }
    out
}

fn render(t: &BTreeMap<String, BTreeSet<String>>) -> String {
    let mut s = String::from(
        "//! GENERATED by tests/std_functions_surface_test.rs (WJ_UPDATE_STD_FUNCTIONS=1): do not edit.\n\
         //! Every function a std module provides in some engine: top-level `fn`s of `std/<m>.wj` and `std/<m>/**/*.wj`,\n\
         //! `pub fn`s of `crates/windjammer-runtime/src/<m>.rs` (or `<m>_mod.rs`), and interpreter builtins `\"<m>::f\"`.\n\n\
         pub static STD_FUNCTIONS: &[(&str, &[&str])] = &[\n",
    );
    for (m, fs) in t {
        let list: Vec<String> = fs.iter().map(|f| format!("\"{f}\"")).collect();
        s.push_str(&format!("    (\"{m}\", &[{}]),\n", list.join(", ")));
    }
    s.push_str("];\n");
    s
}

#[test]
fn std_function_table_is_fresh() {
    let want = compute();
    assert!(want.get("strings").is_some_and(|s| s.contains("trim")), "the scan must find std::strings::trim");
    if std::env::var_os("WJ_UPDATE_STD_FUNCTIONS").is_some() {
        std::fs::write(root().join("src/stdlib_surface/std_functions_table.rs"), render(&want)).unwrap();
        return;
    }
    let have: BTreeMap<String, BTreeSet<String>> = windjammer::stdlib_surface::std_functions::STD_FUNCTIONS
        .iter()
        .map(|(m, fs)| (m.to_string(), fs.iter().map(|f| f.to_string()).collect()))
        .collect();
    assert!(
        have == want,
        "src/stdlib_surface/std_functions_table.rs is stale; regenerate: WJ_UPDATE_STD_FUNCTIONS=1 cargo test --release --test all std_function_table_is_fresh"
    );
}

#[test]
fn scanner_reads_each_source_kind() {
    assert_eq!(top_fns("fn a() {}\npub fn b() {}\n    fn nested() {}\npub async fn c()\n", false), ["a", "b", "c"]);
    assert_eq!(top_fns("fn a() {}\npub fn b() {}\n", true), ["b"]);
}
